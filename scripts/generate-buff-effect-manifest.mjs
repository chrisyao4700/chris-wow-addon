import { readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const addonName = "SlayerUI";
const assetRoot = join(root, "assets", "buff-effects");
const outputPath = join(root, "src", "features", "buff-trigger-effect", "asset-manifest.ts");
const runtimeRoot = `Interface\\AddOns\\${addonName}\\assets\\buff-effects`;

async function walkTgaFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await walkTgaFiles(fullPath)));
      continue;
    }

    if (entry.isFile() && entry.name.endsWith(".tga")) {
      files.push(fullPath);
    }
  }

  return files;
}

async function generateManifest() {
  if (!existsSync(assetRoot)) {
    const contents = `/** Auto-generated by scripts/generate-buff-effect-manifest.mjs */\nexport const bundledBuffEffectPaths = new Set<string>();\n`;
    await writeFile(outputPath, contents);
    console.log("No assets/buff-effects directory found; wrote empty buff effect manifest.");
    return;
  }

  const files = await walkTgaFiles(assetRoot);
  const basePaths = files.map(file => {
    const relativePath = relative(assetRoot, file)
      .replace(/\.tga$/i, "")
      .split(/[/\\]/)
      .join("\\");
    return `${runtimeRoot}\\${relativePath}`;
  });

  const lines = [
    "/** Auto-generated by scripts/generate-buff-effect-manifest.mjs */",
    "export const bundledBuffEffectPaths = new Set<string>([",
    ...basePaths.map(path => `  ${JSON.stringify(path)},`),
    "]);",
    ""
  ];

  await writeFile(outputPath, lines.join("\n"));
  console.log(`Wrote buff effect manifest with ${basePaths.length} bundled texture paths.`);
}

generateManifest().catch(error => {
  console.error(error);
  process.exit(1);
});
