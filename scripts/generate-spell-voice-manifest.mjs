import { readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const addonName = "SlayerUI";
const assetRoot = join(root, "assets", "spell-voices");
const outputPath = join(root, "src", "features", "spell-voice-callout", "asset-manifest.ts");
const runtimeRoot = `Interface\\AddOns\\${addonName}\\assets\\spell-voices`;

async function walkOggFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await walkOggFiles(fullPath)));
      continue;
    }

    if (entry.isFile() && entry.name.endsWith(".ogg")) {
      files.push(fullPath);
    }
  }

  return files;
}

async function generateManifest() {
  if (!existsSync(assetRoot)) {
    const contents = `/** Auto-generated by scripts/generate-spell-voice-manifest.mjs */\nexport const bundledSpellVoicePaths = new Set<string>();\n`;
    await writeFile(outputPath, contents);
    console.log("No assets/spell-voices directory found; wrote empty spell voice manifest.");
    return;
  }

  const files = await walkOggFiles(assetRoot);
  const bundledPaths = files
    .map(filePath => {
      const relativePath = relative(assetRoot, filePath).replaceAll("/", "\\");
      return `${runtimeRoot}\\${relativePath}`;
    })
    .sort((a, b) => a.localeCompare(b));

  const contents = `/** Auto-generated by scripts/generate-spell-voice-manifest.mjs. Do not edit manually. */
export const bundledSpellVoicePaths = new Set<string>([
${bundledPaths.map(path => `  ${JSON.stringify(path)}`).join(",\n")}
]);
`;

  await writeFile(outputPath, contents);
  console.log(`Generated spell voice manifest with ${bundledPaths.length} bundled assets.`);
}

await generateManifest();
